package ee.omnifish.arquillian.container.glassfish.pool.embedded.it;

import java.io.IOException;

import jakarta.servlet.annotation.WebServlet;
import jakarta.servlet.http.HttpServlet;
import jakarta.servlet.http.HttpServletRequest;
import jakarta.servlet.http.HttpServletResponse;

/** Says the system property {@code property} of the child it runs in. */
@WebServlet(urlPatterns = "/setup")
public class SetupServlet extends HttpServlet {
    private static final long serialVersionUID = 1L;

    @Override
    protected void doGet(HttpServletRequest req, HttpServletResponse resp) throws IOException {
        resp.getWriter().print(System.getProperty(req.getParameter("property")));
    }
}
